#!/bin/sh
# builds blake3.wasm and regenerates ../typescript/wasm.ts (inline bytes). quiet by default; -v shows steps
set -e
cd "$(dirname "$0")"
zig cc -target wasm32-freestanding -O3 -nostdlib -mbulk-memory -fno-builtin -Wall \
	-Wl,--no-entry -Wl,--export=room -Wl,--export=hash -Wl,--export-memory \
	-Wl,--initial-memory=65536 -Wl,-z,stack-size=4096 -Wl,--strip-all -Wl,--gc-sections \
	-o blake3.wasm wasm.c
{
	echo "// generated by c/build.sh, do not edit"
	printf 'export const bytes = Uint8Array.from(atob("'
	base64 < blake3.wasm | tr -d '\n'
	echo '"), (c) => c.charCodeAt(0))'
} > ../typescript/wasm.ts
[ "$1" = -v ] && wc -c blake3.wasm
exit 0
