// utis.c and constants.h, generated: the well-known UTIs and types.ts' EXTRA as C tables, and the
// documented constants as macros.
//   deno run --allow-read --allow-write ermine/types/c/utis.ts
//
// the list is ../typescript/utis.json, the constants ../typescript/constants.json, both gathered by
// ../mac/gather.ts. this script only writes them as C; it adds nothing.
import { EXTRA, KNOWN, type Known } from "../typescript/types.ts"
import CONSTANTS from "../typescript/constants.json" with { type: "json" }

const strings = (v: string | readonly string[] | undefined): string[] =>
	v === undefined ? [] : typeof v === "string" ? [v] : [...v]

// a list as a C compound literal: NULL-terminated, or NULL for none
const list = (v: string | readonly string[] | undefined) => {
	const s = strings(v)
	return s.length
		? `(const char *const[]){${s.map((x) => JSON.stringify(x)).join(", ")}, NULL}`
		: "NULL"
}

const row = (t: Known) =>
	[
		JSON.stringify(t.identifier),
		list(t.conformsTo),
		list(t.filenameExtension),
		list(t.mimeType),
		t.referenceURL === undefined ? "NULL" : JSON.stringify(t.referenceURL),
		t.version === undefined ? "NULL" : `&(const long long){${t.version}}`,
	].join(", ")

const table = (name: string, items: readonly Known[]) =>
	`const ty_known ${name}[] = {\n` +
	items.map((t) => `\t{${row(t)}},`).join("\n") +
	`\n};\nconst size_t ${name}_count = ${items.length};\n`

Deno.writeTextFileSync(
	new URL("./utis.c", import.meta.url),
	`// GENERATED by utis.ts: do not edit. the well-known UTIs (typescript/utis.json, gathered by
// mac/gather.ts); ty_extra is types.ts' EXTRA.
#include "types.h"

${table("ty_well_known", KNOWN)}
${table("ty_extra", EXTRA)}`,
)

// plainText: TY_PLAIN_TEXT; threeDContent: TY_THREE_D_CONTENT; mpeg4Movie: TY_MPEG4_MOVIE
const macro = (name: string) =>
	"TY_" +
	name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/([A-Z])([A-Z][a-z])/g, "$1_$2")
		.toUpperCase()

Deno.writeTextFileSync(
	new URL("./constants.h", import.meta.url),
	`// GENERATED by utis.ts: do not edit. swift's documented UTType constants as identifiers
// (typescript/constants.json): UTType.plainText is TY_PLAIN_TEXT, "public.plain-text".
#ifndef TY_CONSTANTS_H
#define TY_CONSTANTS_H

${
		Object.entries(CONSTANTS).map(([name, id]) => `#define ${macro(name)} ${JSON.stringify(id)}`)
			.join("\n")
	}

#endif
`,
)
