// the list is Markus Felten's (arlac77), from his uti library (npm uti@8.11.3), word for word in
// ../typescript/well-known-utis.mjs, with thanks; 0BSD, the licence in
// ../typescript/well-known-utis.LICENSE. this script only writes it as C; it adds nothing.
import { KNOWN } from "../typescript/utis.ts"
import { EXTRA, type Known } from "../typescript/types.ts"

const strings = (v: string | readonly string[] | undefined): string[] =>
	v === undefined ? [] : typeof v === "string" ? [v] : [...v]

// a list as a C compound literal: NULL-terminated, or NULL for none
const list = (v: string | readonly string[] | undefined) => {
	const s = strings(v)
	return s.length
		? `(const char *const[]){${s.map((x) => JSON.stringify(x)).join(", ")}, NULL}`
		: "NULL"
}

const table = (name: string, items: readonly Known[]) =>
	`const ty_known ${name}[] = {\n` +
	items.map((t) =>
		`\t{${JSON.stringify(t.name)}, ${list(t.conformsTo)}, ${list(t.fileNameExtension)}, ${
			list(t.mimeType)
		}},`
	).join("\n") +
	`\n};\nconst size_t ${name}_count = ${items.length};\n`

const out = `// GENERATED by utis.ts: do not edit.
// the well-known UTIs are Markus Felten's (arlac77), from his uti library (npm uti@8.11.3), with
// thanks. licence: 0BSD, typescript/well-known-utis.LICENSE. ty_extra is types.ts' EXTRA.
#include "types.h"

${table("ty_well_known", KNOWN)}
${table("ty_extra", EXTRA)}`

Deno.writeTextFileSync(new URL("./utis.c", import.meta.url), out)
