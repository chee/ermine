// Writes unicode_tables.h: what names.c needs of Unicode to do key() as names.ts does, taken from
// the Unicode data this JavaScript has (so that they cannot differ), by asking it about every
// scalar value.
//   deno run --allow-write files/c/gen_unicode.ts
// decomp: NFD of each scalar value it changes, but Hangul syllables (arithmetic)
// lower, upper: toLowerCase and toUpperCase of each scalar value it changes, but U+03A3 (final sigma)
// ccc: a rank in canonical combining class order, 0 for starters (not the class itself)
// cased, ignorable: the ranges of Cased and Case_Ignorable, for final sigma
const LAST = 0x10ffff
const scalar = (c: number) => c < 0xd800 || c > 0xdfff
const str = String.fromCodePoint
const points = (s: string) => Array.from(s, (c) => c.codePointAt(0)!)

type Row = [cp: number, to: number[]]
const rows = (f: (s: string) => string, skip: (c: number) => boolean = () => false): Row[] => {
	const out: Row[] = []
	for (let c = 0; c <= LAST; c++) {
		if (!scalar(c) || skip(c)) continue
		const s = str(c), t = f(s)
		if (t !== s) out.push([c, points(t)])
	}
	return out
}

const hangul = (c: number) => c >= 0xac00 && c <= 0xd7a3
const decomp = rows((s) => s.normalize("NFD"), hangul)
const lower = rows((s) => s.toLowerCase(), (c) => c === 0x3a3)
const upper = rows((s) => s.toUpperCase())

// ccc: a scalar value that is its own NFD is a non-starter if NFD moves it past U+0301 (class
// 230) or a U+0334 (class 1) past it; the order of two is whether NFD keeps them in order
const stable = (c: number) => scalar(c) && !hangul(c) && str(c).normalize("NFD") === str(c)
const marks: number[] = []
for (let c = 0; c <= LAST; c++) {
	if (!stable(c)) continue
	const s = str(c)
	if (("́" + s).normalize("NFD") !== "́" + s || (s + "̴").normalize("NFD") !== s + "̴") {
		marks.push(c)
	}
}
// a mark's rank: how many others come strictly before it, counting classes
const before = (a: number, b: number) => {
	const ab = (str(a) + str(b)).normalize("NFD") === str(a) + str(b)
	const ba = (str(b) + str(a)).normalize("NFD") === str(b) + str(a)
	return ab && !ba ? -1 : ba && !ab ? 1 : 0
}
const sorted = [...marks].sort((a, b) => before(a, b) || a - b)
const rank = new Map<number, number>()
let r = 0
sorted.forEach((c, i) => {
	if (i > 0 && before(sorted[i - 1], c) !== 0) r++
	rank.set(c, r + 1)
})
if (r + 1 > 255) throw new Error("ranks over a byte")

const ranges = (test: (c: number) => number): [number, number, number][] => {
	const out: [number, number, number][] = []
	for (let c = 0; c <= LAST; c++) {
		const v = scalar(c) ? test(c) : 0
		if (!v) continue
		const last = out[out.length - 1]
		if (last && last[1] === c - 1 && last[2] === v) last[1] = c
		else out.push([c, c, v])
	}
	return out
}
const cased = ranges((c) => /^\p{Cased}$/u.test(str(c)) ? 1 : 0)
const ignorable = ranges((c) => /^\p{Case_Ignorable}$/u.test(str(c)) ? 1 : 0)
const ccc = ranges((c) => rank.get(c) ?? 0)

const hex = (n: number) => "0x" + n.toString(16).toUpperCase()
const pool = (name: string, table: Row[]) => {
	const flat: number[] = []
	const seen = new Map<string, number>()
	const entries = table.map(([c, to]) => {
		const k = to.join(",")
		if (!seen.has(k)) seen.set(k, flat.length), flat.push(...to)
		return `{${hex(c)}, ${seen.get(k)}, ${to.length}}`
	})
	const maxLen = Math.max(...table.map(([, to]) => to.length))
	return `/** ${name}: ${table.length} scalar values, each to at most ${maxLen} */
static const unicode_row unicode_${name}[] = {${wrap(entries)}};
static const uint32_t unicode_${name}_pool[] = {${wrap(flat.map(hex))}};
`
}
const wrap = (items: string[]) => {
	const lines: string[] = []
	let line = ""
	for (const i of items) {
		if (line.length + i.length > 100) lines.push(line), line = ""
		line += i + ", "
	}
	lines.push(line)
	return "\n\t" + lines.map((l) => l.trimEnd()).join("\n\t") + "\n"
}
const spans = (name: string, doc: string, t: [number, number, number][]) =>
	`/** ${doc}: ${t.length} ranges */
static const unicode_span unicode_${name}[] = {${
		wrap(t.map(([a, b, v]) => `{${hex(a)}, ${hex(b)}, ${v}}`))
	}};
`

const out =
	`// unicode_tables.h: Unicode as names.c uses it. Generated by gen_unicode.ts from Deno ${Deno.version.deno}
// (V8 ${Deno.version.v8}); do not edit.

#ifndef UNICODE_TABLES_H
#define UNICODE_TABLES_H

#include <stdint.h>

/** a scalar value and what it becomes: \`len\` values of the pool from \`off\` */
typedef struct {
	uint32_t cp;
	uint16_t off;
	uint8_t len;
} unicode_row;

/** values lo to hi (inclusive) and their rank, 1 where there is only a set */
typedef struct {
	uint32_t lo, hi;
	uint8_t value;
} unicode_span;

${pool("decomp", decomp)}
${pool("lower", lower)}
${pool("upper", upper)}
${spans("ccc", "canonical combining class order: a rank by class, 0 (absent) for starters", ccc)}
${spans("cased", "Cased", cased)}
${spans("ignorable", "Case_Ignorable", ignorable)}
#endif
`
await Deno.writeTextFile(new URL("./unicode_tables.h", import.meta.url), out)
console.log(
	`decomp ${decomp.length} lower ${lower.length} upper ${upper.length} ccc ${ccc.length} (${
		r + 1
	} ranks) cased ${cased.length} ignorable ${ignorable.length}`,
)
